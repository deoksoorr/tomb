// 7×7 픽셀 아이콘. '#' 칸만 currentColor로 칠한다 (폰트에 없는 기호가 이모지로 바뀌는 것을 피한다).

const ICONS = {
  play: [".#.....", ".##....", ".###...", ".####..", ".###...", ".##....", ".#....."],
  pause: [".##.##.", ".##.##.", ".##.##.", ".##.##.", ".##.##.", ".##.##.", ".##.##."],
  next: ["#....#.", "##...#.", "###..#.", "####.#.", "###..#.", "##...#.", "#....#."],
  sound: ["..#..#.", ".##...#", "###.#.#", "###.#.#", "###.#.#", ".##...#", "..#..#."],
  mute: ["..#....", ".##....", "###.#.#", "###..#.", "###.#.#", ".##....", "..#...."],
  note: ["..#####", "..#...#", "..#...#", "..#...#", "###.###", "###.###", "......."],
  info: ["...#...", ".......", "..##...", "...#...", "...#...", "...#...", "..###.."],
  close: ["#.....#", ".#...#.", "..#.#..", "...#...", "..#.#..", ".#...#.", "#.....#"],
  plus: ["...#...", "...#...", "...#...", "#######", "...#...", "...#...", "...#..."],
  minus: [".......", ".......", ".......", "#######", ".......", ".......", "......."],
  target: ["...#...", "..###..", ".#...#.", "##.#.##", ".#...#.", "..###..", "...#..."],
  list: ["#.#####", ".......", "#.#####", ".......", "#.#####", ".......", "#.#####"],
  user: ["..###..", ".#####.", ".#####.", "..###..", ".......", ".#####.", "#######"],
} as const;

export type IconName = keyof typeof ICONS;

const PATHS = Object.fromEntries(
  Object.entries(ICONS).map(([name, rows]) => [
    name,
    rows.flatMap((row, y) => [...row].map((c, x) => (c === "#" ? `M${x} ${y}h1v1h-1z` : ""))).join(""),
  ]),
) as Record<IconName, string>;

export default function PixelIcon({ name, size = 14 }: { name: IconName; size?: number }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 7 7"
      shapeRendering="crispEdges"
      aria-hidden="true"
      focusable="false"
      style={{ flex: "none" }}
    >
      <path d={PATHS[name]} fill="currentColor" />
    </svg>
  );
}
