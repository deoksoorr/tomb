//  [상점에서 사기]·[사냥]처럼 단추를 눌러 걸어가는 길은 도착하면 그대로 들어간다 (단추가 곧 누름).

/** 문 칸 (가로 x0~x1, 문턱 y — 이 아래가 문 밖) */
export type DoorGap = { x0: number; x1: number; y: number };

/** 문 앞 판정 여유 (문 칸 둘레 한 칸쯤) */
export const DOOR_PAD = 16;

/** 문 앞에 서 있다: 문 칸 가로 ± pad, 문턱보다 pad 위부터 그 아래 전부 */
export function atExitDoor(x: number, y: number, door: DoorGap, pad = DOOR_PAD): boolean {
  return x >= door.x0 - pad && x <= door.x1 + pad && y >= door.y - pad;
}
