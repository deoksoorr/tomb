// 별자리 잇기의 별자리 (도감 "별자리" 칸). 순수 데이터라 서버(판 결과 검증·도감 등록)와 화면(게임·도감)이 같이 쓴다.
// 2차 조정: 별자리 하나에 별이 훨씬 많다 (흔함 8~10 · 보통 10~12 · 희귀 12~15 · 전설 16~20).
// 각 별자리는 한 붓으로 그리는 테두리 길(path)을 따라 별을 놓는다 — 꺾이는 곳마다 별, 긴 변은 고르게 나눠 별 수를 채운다 (trace).
// 그래서 박자에 맞춰 이은 선이 곧 그 그림의 테두리가 되고, 다 이으면 art(테두리 + 세부 선)가 빛 선 그림으로 떠오른다.
// 좌표는 0..1 정사각형 (위가 0). 모양은 게임이 화면 비율을 지키며 펼친다.
//
// 나오는 판 (lib/rpg/plan constellationAllowed):
//  - 흔함·보통 = 어느 난이도나 · 희귀 = 어려움 이상 · 전설 = 맑은 밤 판에서만
//  - season이 있으면 그 계절(한국 시각, 곤충 도감과 같은 계절 판정)에만 · dawn이면 새벽(판 시작 시각)에만 — 둘 다 난이도는 상관없다

export type ConstellationRarity = Extract<Rarity, 1 | 2 | 3 | 5>;
type Pt = readonly [number, number];

export type Constellation = {
  id: string;
  name: string;
  rarity: ConstellationRarity;
  /** 이 순서대로 잇는다 */
  stars: readonly Pt[];
  /** 다 이으면 떠오르는 그림 (선 여러 줄) — 첫 줄은 별을 이은 테두리 */
  art: readonly (readonly Pt[])[];
  /** 무슨 그림인지 한 줄 (도감·결과) */
  shape: string;
  desc: string;
  /** 이 계절에만 */
  season?: Season;
  /** 새벽에만 */
  dawn?: boolean;
};

/** 희귀도별 별 수 범위 (시험이 지킨다) */
export const STAR_COUNT: Record<ConstellationRarity, readonly [number, number]> = { 1: [8, 10], 2: [10, 12], 3: [12, 15], 5: [16, 20] };

const r3 = (v: number) => Math.round(v * 1000) / 1000;

/** 원·호를 점 k+1개로 (그림용). a0·a1은 도(°), 0 = 오른쪽, 90 = 아래 */
function arc(cx: number, cy: number, rx: number, ry: number, a0: number, a1: number, k = 12): Pt[] {
  const out: Pt[] = [];
  for (let i = 0; i <= k; i++) {
    const a = ((a0 + ((a1 - a0) * i) / k) * Math.PI) / 180;
    out.push([r3(cx + Math.cos(a) * rx), r3(cy + Math.sin(a) * ry)]);
  }
  return out;
}
const ring = (cx: number, cy: number, r: number, k = 14) => arc(cx, cy, r, r, 0, 360, k);
const rect = (x0: number, y0: number, x1: number, y1: number): Pt[] => [
  [x0, y0],
  [x1, y0],
  [x1, y1],
  [x0, y1],
  [x0, y0],
];
const seg = (x0: number, y0: number, x1: number, y1: number): Pt[] => [
  [x0, y0],
  [x1, y1],
];

/** 테두리 길의 꺾이는 점을 모두 별로 두고, 남는 별은 가장 긴 변부터 고르게 나눠 채운다 (n개) */
export function trace(path: readonly Pt[], n: number): Pt[] {
  const pts = path.filter((p, i) => i === 0 || p[0] !== path[i - 1][0] || p[1] !== path[i - 1][1]);
  const lens = pts.slice(1).map((p, i) => Math.hypot(p[0] - pts[i][0], p[1] - pts[i][1]));
  const parts = lens.map(() => 1);
  for (let k = pts.length; k < n; k++) {
    let best = 0;
    for (let i = 1; i < lens.length; i++) if (lens[i] / parts[i] > lens[best] / parts[best]) best = i;
    parts[best]++;
  }
  const out: Pt[] = [pts[0]];
  lens.forEach((_, i) => {
    const [x0, y0] = pts[i];
    const [x1, y1] = pts[i + 1];
    for (let j = 1; j <= parts[i]; j++) out.push([r3(x0 + ((x1 - x0) * j) / parts[i]), r3(y0 + ((y1 - y0) * j) / parts[i])]);
  });
  return out;
}

type Def = Omit<Constellation, "stars" | "art"> & { path: Pt[]; n: number; detail: Pt[][] };
const def = (d: Def): Constellation => {
  const { path, n, detail, ...rest } = d;
  return { ...rest, stars: trace(path, n), art: [path, ...detail] };
};

