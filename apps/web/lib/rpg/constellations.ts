import type { Rarity } from "../forage/catalog";

// 별자리 잇기의 별자리 (도감 "별자리" 칸). 순수 데이터라 서버(판 결과 검증·도감 등록)와 화면(게임·도감)이 같이 쓴다.
// 각 별자리는 정해진 모양: stars = 별 좌표(0..1 정사각형 안, 위가 0) — 이 순서대로 박자에 맞춰 잇는다.
// art = 다 이었을 때 그 위로 떠오르는 가는 빛 선 그림 (선 여러 줄, 같은 0..1 좌표). 모양은 게임이 화면 비율을 지키며 펼친다.
//
// 희귀도 (도감 희귀도 표기를 그대로 쓴다): 1 흔함·2 보통 = 어느 난이도나 · 3 희귀 = 어려움 이상 · 5 전설 = 맑은 밤 보너스 판에서만.
// 별 수는 5·6·7개 (예전 별 무리 크기 그대로) — 그룹 크기는 박자 계획이 먼저 정하고, 같은 크기의 별자리 중에서 고른다.

export type ConstellationRarity = Extract<Rarity, 1 | 2 | 3 | 5>;
type Pt = readonly [number, number];

export type Constellation = {
  id: string;
  name: string;
  rarity: ConstellationRarity;
  /** 이 순서대로 잇는다 (5~7개) */
  stars: readonly Pt[];
  /** 다 이으면 떠오르는 그림 (선 여러 줄) */
  art: readonly (readonly Pt[])[];
  /** 무슨 그림인지 한 줄 (도감·결과) */
  shape: string;
  desc: string;
};

/** 원·호를 점 n개로 (그림용). a0·a1은 도(°), 0 = 오른쪽, 90 = 아래 */
function arc(cx: number, cy: number, rx: number, ry: number, a0: number, a1: number, n = 12): Pt[] {
  const out: Pt[] = [];
  for (let i = 0; i <= n; i++) {
    const a = ((a0 + ((a1 - a0) * i) / n) * Math.PI) / 180;
    out.push([+(cx + Math.cos(a) * rx).toFixed(3), +(cy + Math.sin(a) * ry).toFixed(3)]);
  }
  return out;
}
const ring = (cx: number, cy: number, r: number, n = 14) => arc(cx, cy, r, r, 0, 360, n);
const rect = (x0: number, y0: number, x1: number, y1: number): Pt[] => [
  [x0, y0],
  [x1, y0],
  [x1, y1],
  [x0, y1],
  [x0, y0],
];

